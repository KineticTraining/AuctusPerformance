import {
  CATEGORY_SUMMARIES,
  slugifyExercise,
  type BodyPartFilter,
  type DemandTier,
  type EquipmentBucket,
  type ExerciseCategory,
  type ExerciseEntry,
  type TrainingAgeGroup,
  type TrainingExperienceLevel,
  type TrainingSport,
} from "./types";

interface LowerSeedItem {
  name: string;
  subcategory: string;
  equipment: EquipmentBucket[];
  bodyParts: BodyPartFilter[];
  primaryMuscles: string[];
  secondaryMuscles: string[];
  movementPattern: string;
  difficulty: TrainingExperienceLevel;
  demandTier: DemandTier;
  sports?: TrainingSport[];
  ageGroups?: TrainingAgeGroup[];
  purpose: string;
  steps: string[];
  pairings: string[];
  image?: string;
}

const ALL_SPORTS: TrainingSport[] = [
  "General Gym / Strength",
  "Basketball",
  "Soccer / Field Sports",
  "Track & Sprint",
  "Court / Combat",
];

function buildEntries(
  catIdx: number,
  category: ExerciseCategory,
  items: LowerSeedItem[],
): ExerciseEntry[] {
  const defaultImg = CATEGORY_SUMMARIES[category].defaultImage;
  return items.map((item) => ({
    id: slugifyExercise(catIdx, item.name),
    name: item.name,
    category,
    subcategory: item.subcategory,
    equipment: item.equipment,
    bodyParts: item.bodyParts,
    primaryMuscles: item.primaryMuscles,
    secondaryMuscles: item.secondaryMuscles,
    movementPattern: item.movementPattern,
    difficulty: item.difficulty,
    demandTier: item.demandTier,
    sports: item.sports ?? ALL_SPORTS,
    ...(item.ageGroups ? { ageGroups: item.ageGroups } : {}),
    purpose: item.purpose,
    steps: item.steps,
    pairings: item.pairings,
    image: item.image ?? defaultImg,
  }));
}

