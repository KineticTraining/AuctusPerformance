import {
  CATEGORY_SUMMARIES,
  slugifyExercise,
  type BodyPartFilter,
  type DemandTier,
  type EquipmentBucket,
  type ExerciseCategory,
  type ExerciseEntry,
  type TrainingAgeGroup,
  type TrainingExperienceLevel,
  type TrainingSport,
} from "./types";

interface SeedRow {
  name: string;
  subcategory: string;
  equipment: EquipmentBucket[];
  bodyParts: BodyPartFilter[];
  primaryMuscles: string[];
  secondaryMuscles: string[];
  movementPattern: string;
  difficulty: TrainingExperienceLevel;
  demandTier: DemandTier;
  sports?: TrainingSport[];
  ageGroups?: TrainingAgeGroup[];
  purpose: string;
  steps: string[];
  pairings: string[];
  image?: string;
}

const ALL_SPORTS: TrainingSport[] = [
  "General Gym / Strength",
  "Basketball",
  "Soccer / Field Sports",
  "Track & Sprint",
  "Court / Combat",
];

function makeCat(catIdx: number, category: ExerciseCategory, rows: SeedRow[]): ExerciseEntry[] {
  const defaultImg = CATEGORY_SUMMARIES[category].defaultImage;
  return rows.map((r) => ({
    id: slugifyExercise(catIdx, r.name),
    name: r.name,
    category,
    subcategory: r.subcategory,
    equipment: r.equipment,
    bodyParts: r.bodyParts,
    primaryMuscles: r.primaryMuscles,
    secondaryMuscles: r.secondaryMuscles,
    movementPattern: r.movementPattern,
    difficulty: r.difficulty,
    demandTier: r.demandTier,
    sports: r.sports ?? ALL_SPORTS,
    ...(r.ageGroups ? { ageGroups: r.ageGroups } : {}),
    purpose: r.purpose,
    steps: r.steps,
    pairings: r.pairings,
    image: r.image ?? defaultImg,
  }));
}

